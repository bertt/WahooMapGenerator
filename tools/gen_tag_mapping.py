"""Generates data/tag-mapping.csv from the tag table of a reference Wahoo tile.

Usage:
    wahoo-map-generator inspect 84.map.lzma > data/reference-tags.tsv
    uv run python tools/gen_tag_mapping.py data/reference-tags.tsv data/tag-mapping.csv

The reference tile provides the Wahoo tag list (and its order, which defines the tag ids)
and the lowest zoom level at which each tag appears. This script adds the knowledge of which
OpenStreetMap tags map to each Wahoo tag.
"""

import sys

DEFAULT_ZOOM = 13

# Wahoo key -> (OSM key, value prefix to strip). Wahoo prefixes some values.
RENAMED = {
    "bicycle": ("bicycle", "bic_"),
    "foot": ("foot", "ft_"),
    "access": ("access", "acc_"),
    "oneway:bicycle": ("oneway:bicycle", "ow_bic_"),
    "mtb_scale": ("mtb:scale", "mtbs_"),
    "mtb_scale_uphill": ("mtb:scale:uphill", "mtbu_"),
    "ford": ("ford", "fd_"),
    "ladder": ("ladder", "ld_"),
    "embankment": ("embankment", "emb_"),
    "intermittent": ("intermittent", "wwi_"),
    "seasonal": ("seasonal", "seas_"),
    "toll": ("toll", "tl_"),
    "cycleway:oneway": ("cycleway:oneway", "cw_ow_"),
}

# Wahoo cycleway tags -> OSM tags, keyed by the full Wahoo tag.
CYCLEWAY = {}
for kind, osm_value in (("lane", "lane"), ("shared", "shared_lane"), ("track", "track"), ("shoulder", "shoulder")):
    for side in ("both", "right", "left"):
        osm = [f"cycleway:{side}={osm_value}"]
        if side == "both":
            osm.append(f"cycleway={osm_value}")
        CYCLEWAY[f"cycleway_{kind}=cw_{kind}_{side}"] = osm

SURFACE = {
    "asphalt": ["asphalt"],
    "smooth_paved": ["concrete", "paving_stones", "concrete:plates", "concrete:lanes", "metal", "wood"],
    "paved": ["paved"],
    "compacted": ["compacted", "fine_gravel"],
    "unpaved": ["unpaved"],
    "rough_paved": ["sett", "cobblestone", "unhewn_cobblestone", "bricks"],
    "raw": ["dirt", "ground", "earth", "mud", "sand", "grass"],
    "gravel": ["gravel", "pebblestone"],
}

# Tags that are known in the header but have no OSM source that we can map reliably.
HEADER_ONLY = {
    "hike_node=rwn",
    "cycle_node=NLBE",
    "cycleway_lane=cw_lane_oneway",
    "cycleway_track=cw_track_oneway",
}

OTHER = {"natural=nat_stone": ["natural=stone"]}

# Keys that describe another feature instead of being a feature themselves.
MODIFIERS = {
    "way": {
        "surface", "oneway", "oneway:bicycle", "bicycle", "foot", "access", "tracktype",
        "trail_visibility", "leaf_type", "bridge", "tunnel", "cycleway_lane", "cycleway_shared",
        "cycleway_track", "cycleway_shoulder", "cycleway:oneway", "mtb_scale", "mtb_scale_uphill",
        "toll", "seasonal", "intermittent", "embankment", "area", "ford", "ladder", "location",
        "lock", "sport", "religion", "protect_class", "protection_title", "admin_level",
        "shelter_type",
    },
    "poi": {
        "surface", "bicycle", "access", "religion", "information", "shelter_type",
        "drinking_water", "capital", "generator:source", "station", "whitewater",
    },
}


def osm_tags(wahoo_tag):
    if wahoo_tag in HEADER_ONLY:
        return []
    if wahoo_tag in CYCLEWAY:
        return CYCLEWAY[wahoo_tag]
    if wahoo_tag in OTHER:
        return OTHER[wahoo_tag]
    key, value = wahoo_tag.split("=", 1)
    if key == "surface":
        return [f"surface={v}" for v in SURFACE[value]]
    if key in RENAMED:
        osm_key, prefix = RENAMED[key]
        return [f"{osm_key}={value.removeprefix(prefix)}"]
    return [wahoo_tag]


def main(src, dst):
    rows = []
    for line in open(src, encoding="utf-8"):
        parts = line.rstrip("\n").split("\t")
        if len(parts) != 4:
            continue
        kind, tag, _count, zoom = parts
        zoom = DEFAULT_ZOOM if zoom == "-" else int(zoom)
        key = tag.split("=", 1)[0]
        primary = "false" if key in MODIFIERS[kind] else "true"
        for source in osm_tags(tag) or [""]:
            rows.append(f"{kind},{source},{tag},{zoom},{primary}")
    with open(dst, "w", encoding="utf-8", newline="\n") as out:
        out.write("# Generated by tools/gen_tag_mapping.py from a reference Wahoo tile.\n")
        out.write("# kind,osm_tag,wahoo_tag,min_zoom,primary\n")
        out.write("\n".join(rows) + "\n")
    print(f"wrote {len(rows)} rules to {dst}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
